/**
 * Приводит feature.properties.name из GeoJSON к ключу districtsData.
 * "городской округ Казань" -> "Казань", остальные названия районов совпадают напрямую.
 */
function normalizeDistrictKey(rawName) {
  if (!rawName) return rawName;
  const prefix = 'городской округ ';
  return rawName.startsWith(prefix) ? rawName.slice(prefix.length) : rawName;
}
